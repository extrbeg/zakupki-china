type Cell = string | number | boolean;

/** Serial-число даты Google Sheets (эпоха 1899-12-30). */
export function serial(iso: string): number {
  const [y, m, d] = iso.split('-').map(Number);
  return (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86_400_000;
}

const colIndex = (letters: string) => [...letters].reduce((n, ch) => n * 26 + (ch.charCodeAt(0) - 64), 0) - 1;

/** Строка листа из пар «буква колонки → значение»; пустые ячейки внутри — '', хвост обрезан. */
function row(cells: Record<string, Cell>): Cell[] {
  const out: Cell[] = [];
  for (const [col, v] of Object.entries(cells)) {
    const i = colIndex(col);
    while (out.length < i) out.push('');
    out[i] = v;
  }
  return out;
}

