/** Номер версии подставляет сборка из package.json (vite.config.ts); без сборки (тесты) — последняя запись истории. */
export const APP_VERSION: string = import.meta.env.VITE_APP_VERSION || CHANGELOG[0].version;

/** Запись текущей версии; если сборка новее истории — пустая запись с номером сборки. */
export const CURRENT_ENTRY: ChangelogEntry =
  CHANGELOG.find((e) => e.version === APP_VERSION) ?? { version: APP_VERSION, date: CHANGELOG[0].date, added: [], fixed: [] };

/** Сравнение номеров вида 1.2.3: <0, если a старше b. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((n) => Number.parseInt(n, 10) || 0);
  const pb = b.split('.').map((n) => Number.parseInt(n, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i += 1) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

/** Версии новее `seen` и не новее `current`, от новой к старой. */
export function entriesSince(seen: string, current: string = APP_VERSION): ChangelogEntry[] {
  return CHANGELOG.filter((e) => compareVersions(e.version, seen) > 0 && compareVersions(e.version, current) <= 0);
}
